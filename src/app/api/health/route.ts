import { NextResponse } from "next/server";

export function GET() {
  return new NextResponse(
    JSON.stringify({ status: "healthy" }),
    {
      status: 200,
      headers: {
        "Content-Type": "application/json",
        "Cache-Control": "no-store, no-cache, must-revalidate, proxy-revalidate",
        "Pragma": "no-cache",
        "Expires": "0",
      },
    }
  );
}